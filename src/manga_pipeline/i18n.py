class Translator:
    """Process-wide singleton for UI string lookup."""

    def __init__(self, lang: str = "en"):
        self._lang = lang if lang in SUPPORTED_LANGUAGES else "en"

    @property
    def lang(self) -> str:
        return self._lang

    def set_language(self, lang: str) -> None:
        if lang in SUPPORTED_LANGUAGES:
            self._lang = lang

    def tr(self, key: str, **kwargs) -> str:
        table = _STRINGS.get(self._lang) or _STRINGS["en"]
        text = table.get(key) or _STRINGS["en"].get(key) or key
        if kwargs:
            try:
                return text.format(**kwargs)
            except (KeyError, IndexError):
                return text
        return text


_translator = Translator()


def set_language(lang: str) -> None:
    _translator.set_language(lang)


def get_language() -> str:
    return _translator.lang


def tr(key: str, **kwargs) -> str:
    return _translator.tr(key, **kwargs)
